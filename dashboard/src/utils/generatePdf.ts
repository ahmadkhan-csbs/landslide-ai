import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export const generateEmergencySitRep = () => {
  const doc = new jsPDF();
  
  // Header
  doc.setFontSize(20);
  doc.setTextColor(220, 38, 38); // Red
  doc.text('NATIONAL DISASTER MANAGEMENT AUTHORITY', 105, 20, { align: 'center' });
  
  doc.setFontSize(14);
  doc.setTextColor(0, 0, 0);
  doc.text('EMERGENCY SITUATION REPORT (SITREP)', 105, 28, { align: 'center' });
  
  // Meta Info
  doc.setFontSize(10);
  doc.text(`Date & Time: ${new Date().toLocaleString()}`, 14, 45);
  doc.text(`Generated By: Landslide AI Predictor Engine`, 14, 52);
  doc.text(`Region: North Eastern Region (NER), India`, 14, 59);

  doc.setLineWidth(0.5);
  doc.line(14, 65, 196, 65);
  
  // Section 1: Alert Summary
  doc.setFontSize(12);
  doc.setTextColor(220, 38, 38);
  doc.setFont("helvetica", "bold");
  doc.text('1. CRITICAL ACTIVE ALERTS', 14, 75);
  
  autoTable(doc, {
    startY: 80,
    head: [['Location', 'Risk Level', 'Trigger', 'Predicted Rainfall']],
    body: [
      ['Mangan, Sikkim', 'HIGH (92%)', 'GLOF + Heavy Rain', '124 mm / 24h'],
      ['Silchar, Assam', 'HIGH (88%)', 'Fluvial Erosion', '98 mm / 24h'],
      ['Cherrapunji, Meghalaya', 'MEDIUM (65%)', 'Extreme Rain', '210 mm / 24h'],
      ['Dima Hasao, Assam', 'HIGH (84%)', 'Slope Instability', '115 mm / 24h'],
    ],
    theme: 'grid',
    headStyles: { fillColor: [220, 38, 38] },
    styles: { fontSize: 10 },
  });

  // Section 2: Evacuation Status
  const finalY = (doc as any).lastAutoTable.finalY || 80;
  
  doc.setFontSize(12);
  doc.setTextColor(37, 99, 235); // Blue
  doc.text('2. LOGISTICS & EVACUATION ROUTES', 14, finalY + 15);
  
  autoTable(doc, {
    startY: finalY + 20,
    head: [['Route', 'Status', 'ETA for Convoy']],
    body: [
      ['Guwahati to Silchar', 'SAFE (Clear)', '6h 12m'],
      ['Gangtok to Mangan', 'BLOCKED (Debris)', 'N/A'],
      ['Shillong to Cherrapunji', 'CAUTION (Heavy Rain)', '2h 45m'],
      ['Tezpur to Tawang', 'SAFE (Clear)', '5h 30m'],
    ],
    theme: 'grid',
    headStyles: { fillColor: [37, 99, 235] },
    styles: { fontSize: 10 },
  });

  // Section 3: AI Confidence
  const finalY2 = (doc as any).lastAutoTable.finalY || finalY + 20;
  
  doc.setFontSize(12);
  doc.setTextColor(16, 185, 129); // Green
  doc.text('3. AI PREDICTIVE ENGINE METRICS', 14, finalY2 + 15);
  
  autoTable(doc, {
    startY: finalY2 + 20,
    head: [['Metric', 'Value']],
    body: [
      ['Model Used', 'Ensemble (U-Net + XGBoost)'],
      ['Overall Accuracy', '97.4% (Cross-validated)'],
      ['Satellite Images Scanned', '4,280'],
      ['Ground Sensors Active', '112 / 120'],
      ['False Positive Rate', '< 2.1%'],
    ],
    theme: 'grid',
    headStyles: { fillColor: [16, 185, 129] },
    styles: { fontSize: 10 },
  });
  
  // Footer
  doc.setFontSize(8);
  doc.setTextColor(100, 100, 100);
  doc.setFont("helvetica", "normal");
  doc.text('CONFIDENTIAL: For Official Use Only. Generated by Landslide AI PRO Hackathon Prototype.', 105, 285, { align: 'center' });

  // Download
  doc.save(`Official_SitRep_${new Date().toISOString().slice(0,10)}.pdf`);
};
